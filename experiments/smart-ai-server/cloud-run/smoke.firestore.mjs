assert.equal(await s.recoverExpired(uid),false);
assert.equal((await s.readCredits(uid)).remaining,15);
assert.equal((await s.reserveUsage(winner)).status,409);
await assert.rejects(s.finishOutcome({...winner,status:'completed'}));
const c={uid,requestId:randomUUID()};
assert.equal((await s.reserveUsage(c)).status,200);
await s.finishOutcome({...c,status:'completed'});
