'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const runner=read('tests/integrated-security-audit/run.cjs');
const http=read('js/services/httpFinanceLab.js');
const telemetry=read('js/services/httpTelemetryLab.js');
const backup=read('js/services/backupRecoveryLab.js');
const auth=read('js/services/emulatorAuthBackendLab.js');
const config=JSON.parse(read('tests/emulator-http-finance/firebase.json'));
let n=0;
function test(name,fn){fn();console.log('APROVADO:',name);n++;}
test('Firestore somente loopback',()=>assert.equal(config.emulators.firestore.host,'127.0.0.1'));
test('Auth somente loopback',()=>assert.equal(config.emulators.auth.host,'127.0.0.1'));
test('runner exige dependencias isoladas',()=>assert.match(runner,/RAYTECH_SAFE_NODE_MODULES/));
test('runner remove credenciais externas',()=>assert.match(runner,/delete env.GOOGLE_APPLICATION_CREDENTIALS/));
test('runner exige codigo de saida zero',()=>assert.match(runner,/r.status===0/));
test('runner exige total exato de testes',()=>assert.match(runner,/output.includes\(expected\)/));
test('runner exige encerramento dos emuladores',()=>assert.match(runner,/Script exited successfully \(code 0\)/));
test('runner registra falhas de bateria',()=>assert.match(runner,/FALHA NA BATERIA/));
test('runner bloqueia aprovacao de producao',()=>assert.match(runner,/NOT_READY_FOR_PRODUCTION/));
test('HTTP exige autenticacao',()=>assert.match(http,/parseBearer\(header/));
test('telemetria usa lista de campos',()=>assert.match(telemetry,/event:'http_request'/));
test('backup valida checksum antes de restaurar',()=>assert.match(backup,/const next=verifyBackup\(envelope\)/));
test('Firebase Admin valida token',()=>assert.match(auth,/verifyIdToken\(token\)/));
test('runner nao executa npm deploy',()=>assert(!/firebase deploy|npm publish|git push/.test(runner)));
console.log('RESULTADO: '+n+'/14 TESTES APROVADOS');
