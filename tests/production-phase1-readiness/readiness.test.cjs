'use strict';
const assert=require('node:assert/strict');
const {audit,RISKS}=require('../../js/services/phase1IntegrationReadinessLab.js');
const {syntheticHistory}=require('../../js/services/financeIntegrityE2ELab.js');
const {createBackup,verifyBackup}=require('../../js/services/backupRecoveryLab.js');
const {validateSnapshot,sanitizeSyncPayload}=require('../../js/services/productionDataContractLab.js');
const {migrate,verify,createSession,balances}=require('../../js/services/reversibleFinanceMigrationLab.js');
const {plan}=require('../../js/services/installmentDeletionPolicyLab.js');
const {memoryDisk,open}=require('../../js/services/installmentPersistenceRecoveryLab.js');
const clone=x=>JSON.parse(JSON.stringify(x));
let passed=0;
function test(name,fn){fn();passed++;console.log('APROVADO:',name);}
const base=()=>syntheticHistory();
const result=audit();
test('veredito bloqueia integracao',()=>assert.equal(result.verdict,'NOT_READY_FOR_INTEGRATION'));
test('contrato sintetico aceito',()=>assert.equal(result.contract.ok,true));
test('migracao sintetica aceita',()=>assert.equal(result.migration.ok,true));
test('migracao recupera original',()=>assert.equal(result.migration.value.sameOriginal,true));
test('migracao preserva saldos',()=>assert.equal(result.migration.value.sameBalances,true));
test('migracao preserva fingerprint',()=>assert.equal(result.migration.value.sameFingerprint,true));
test('auditoria ponta a ponta executada',()=>assert.equal(result.roundTrip.ok,true));
test('auditoria ponta a ponta quatro meses',()=>assert.equal(result.roundTrip.value,4));
test('backup sintetico verificado',()=>assert.equal(result.backup.ok,true));
test('backup preserva fingerprint',()=>assert.equal(result.backup.value,true));
test('sanitizacao do contrato aceita snapshot',()=>assert.equal(result.sanitized.ok,true));
test('persistencia experimental executada',()=>assert.equal(result.deletion.ok,true));
test('persistencia preserva exclusao',()=>assert.equal(result.deletion.value.preserved,true));
test('recriacao bloqueia parcela',()=>assert.equal(result.deletion.value.blocked,true));
test('ponte com tombstones nao aceita pelo contrato',()=>assert.equal(result.schemaBridge.ok,false));
test('ponte rejeita campos adicionais',()=>assert.equal(result.schemaBridge.error,'unexpected_fields'));
test('parcela legada sem origem nao aceita politica',()=>assert.equal(result.legacyCard.ok,false));
test('origem legada exige revisao',()=>assert.equal(result.legacyCard.error,'ambiguous_legacy_origin'));
test('dez riscos catalogados',()=>assert.equal(result.riskCount,10));
test('identificadores de risco unicos',()=>assert.equal(new Set(RISKS.map(r=>r.id)).size,10));
test('todos os riscos bloqueados',()=>assert.ok(RISKS.every(r=>r.status==='BLOCKED')));
test('todos possuem criterio verificavel',()=>assert.ok(RISKS.every(r=>r.criterion.length>30)));
test('todos possuem severidade',()=>assert.ok(RISKS.every(r=>['HIGH','MEDIUM','CRITICAL'].includes(r.severity))));
test('exclusoes constam como risco',()=>assert.ok(RISKS.some(r=>r.id==='I01')));
test('legado consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I02')));
test('backup autenticado consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I03')));
test('backup completo consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I04')));
test('persistencia real consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I05')));
test('regras reais constam como risco',()=>assert.ok(RISKS.some(r=>r.id==='I06')));
test('isolamento consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I07')));
test('contrato completo consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I08')));
test('rollback duravel consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I09')));
test('LGPD consta como risco',()=>assert.ok(RISKS.some(r=>r.id==='I10')));
test('snapshot original nao alterado',()=>{const s=base(),before=clone(s);audit(s);assert.deepEqual(s,before);});
test('resultado de auditoria independente',()=>{const a=audit();a.risks[0].status='READY';assert.equal(audit().risks[0].status,'BLOCKED');});
test('contrato rejeita tombstones externos',()=>assert.throws(()=>sanitizeSyncPayload({...base(),deletions:{}}),e=>e.code==='unexpected_fields'));
test('backup nao remove tombstones por conta propria',()=>{const s={selectedMonth:'2026-10',months:{'2026-10':{cardExpenses:[]}},deletions:{'2026-11':['orig:2']}};assert.deepEqual(verifyBackup(createBackup(s)).deletions['2026-11'],['orig:2']);});
test('backup aceita schema que contrato nao valida',()=>{const s={selectedMonth:'2026-10',months:{'2026-10':{cardExpenses:[]}},deletions:{}};assert.ok(createBackup(s));assert.throws(()=>validateSnapshot(s));});
test('restauracao de tombstones depende de revisao',()=>{const s={selectedMonth:'2026-10',months:{'2026-10':{cardExpenses:[]}},deletions:{}};const d=memoryDisk(s),a=open(d),b=open(d);a.mark('2026-11','orig',2);assert.throws(()=>b.mark('2026-11','orig',2),e=>e.code==='revision_conflict');});
test('exclusao por origem nao apaga outra',()=>{const c=(id,origin)=>({id,isInstallment:true,installmentOriginId:origin,currentInstallment:1,installments:3});const p=plan([c('a','orig'),c('b','other')],'2026-11',['orig:2']);assert.equal(p.created,1);});
test('migracao reversivel preserva checksum',()=>{const s=base(),p=migrate(s);assert.equal(verify(p).sourceHash,p.sourceHash);});
test('revisao de migracao impede dupla aplicacao',()=>{const s=base(),p=migrate(s),session=createSession(s);session.apply(p,0);assert.throws(()=>session.apply(p,0),e=>e.code==='revision_conflict');});
test('saldo de investimentos reduz saldo',()=>{const s=base(),before=balances(s)['2026-12'];s.months['2026-12'].expenses.find(x=>x.category==='investimentos').amount+=50;assert.equal(balances(s)['2026-12'],before-50);});
test('matriz nao afirma producao pronta',()=>assert.notEqual(result.verdict,'READY_FOR_PRODUCTION'));
console.log('RESULTADO: '+passed+'/44 TESTES APROVADOS');
